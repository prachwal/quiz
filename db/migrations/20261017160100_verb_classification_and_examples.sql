SET difficulty_id = (
  SELECT d.id FROM difficulty_levels d WHERE d.code = CASE
    WHEN pt.code = 'AAA' THEN 'easy'
    WHEN pt.code = 'ABB' AND po.code = 'core' THEN 'easy'
    WHEN pt.code = 'ABC' AND po.code <> 'core' THEN 'hard'
    ELSE 'medium'
  END
)
FROM verb_patterns pt, popularity_tiers po
WHERE pt.id = v.pattern_id AND po.id = v.popularity_id;

